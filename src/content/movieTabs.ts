/*
 * GENERATED DATA — fingered tab for the movie songs in movieSongs.ts. Do not
 * edit by hand.
 *
 * Five pieces were read note for note from the MIDI file of a Mutopia Project
 * edition (a data file; nothing in it was executed), quantised to 1/24 of a
 * quarter note, and then given a string and fret by the same small search that
 * made classicalTabs.ts: every fretted note sounding together fits a 5-fret
 * reach, open strings are preferred, nothing above the 15th fret is used, and
 * no string is asked to sound two notes at once. The fingering is ours; the
 * notes, rhythm and tempo are the edition's.
 *
 * They are arrangements for one guitar, not whole pieces, and the octave is
 * chosen for the neck: a bass note below the guitar's low E is taken up an
 * octave. What was kept of each:
 *   - Mountain King (Grieg): the right-hand theme of bars 2-17, up an octave.
 *   - Canon (Pachelbel): the first violin and the cello of bars 1-10, the
 *     violin down an octave.
 *   - Gymnopédie No. 1 (Satie): the melody (the top voice) and the bass note
 *     of bars 5-18, the melody down an octave.
 *   - Air (Bach): the flute's melody and the walking bass of the guitar part,
 *     bars 1-12, both down an octave; a few bass notes sit an octave higher
 *     where the left hand could not otherwise reach them.
 *   - The Entertainer (Joplin): the right hand's tune (the lower of its
 *     doubled octaves), down an octave, and the left hand's bass notes on the
 *     beat, as written, bars 5-20.
 * movieSongs.test.ts pins the first bars' pitches so a fingering bug cannot
 * change the music.
 *
 * The Dies irae and the three guitarRot originals were not read from a file:
 * they were written as lists of pitches and fingered by the same search.
 *
 * A row is [start, stringIndex, fret, length]: start and length are in
 * 1/24 of a quarter note (so 24 is one beat), stringIndex 0 is the low E.
 */

